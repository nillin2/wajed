let currentLang = localStorage.getItem('wadj-lang') || 'ar';

function t(key) {
  const dict = I18N[currentLang] || I18N.ar;
  return dict[key] || I18N.ar[key] || key;
}

function tAttr(key, attr) {
  const dict = I18N[currentLang] || I18N.ar;
  const val = dict[key];
  return val ? val : (I18N.ar[key] || key);
}

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = (I18N[lang] || I18N.ar)[key];
    if (val) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = (I18N[lang] || I18N.ar)[key];
    if (val) el.setAttribute('placeholder', val);
  });
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const btnLang = btn.getAttribute('data-lang');
    btn.classList.toggle('active', btnLang === lang);
  });
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) document.title = tAttr(titleEl.getAttribute('data-i18n'), 'textContent');
  localStorage.setItem('wadj-lang', lang);
}

function getCurrentLang() { return currentLang; }
function getDirection() { return currentLang === 'ar' ? 'rtl' : 'ltr'; }
